// services/artifact-exporter.js
/**
 * Artifact Markdown Exporter & System Clipboard Bridge
 * 
 * Part of Google Antigravity-inspired Windows Attached Sidebar Task Hub (Milestone M3).
 * Provides:
 *   - Formats Artifact into clean GitHub-flavored Markdown with YAML frontmatter header (---).
 *   - 1-Click Clipboard serialization and system copy.
 *   - Persistent local disk export to artifacts/artifact-<type>-<id>.md.
 */

const fs = require('fs');
const path = require('path');

/**
 * Serialize an Artifact object into GitHub-flavored Markdown with YAML frontmatter.
 * 
 * @param {object} artifact - The artifact to format
 * @returns {string} Formatted Markdown text
 */
function formatArtifactMarkdown(artifact) {
  if (!artifact) return '';

  const steps = artifact.steps || (artifact.payload && (artifact.payload.steps || artifact.payload.actions)) || [];
  const total = artifact.progress?.totalSteps ?? steps.length;
  const completed = artifact.progress?.completedSteps ?? steps.filter(s => s.completed).length;
  const percent = artifact.progress?.percent ?? (total > 0 ? Math.round((completed / total) * 100) : 0);
  const createdDate = new Date(artifact.createdAt || Date.now()).toISOString();
  const updatedDate = new Date(artifact.updatedAt || Date.now()).toISOString();

  const lines = [
    '---',
    `id: ${artifact.id}`,
    `type: ${artifact.type || 'plan'}`,
    `command: ${artifact.command || '/plan'}`,
    `title: ${artifact.title || '探索任务产出物'}`,
    `created: ${createdDate}`,
    `updated: ${updatedDate}`,
    `status: ${artifact.status || 'active'}`,
    `progress: ${percent}% (${completed}/${total} completed)`,
    '---',
    '',
    `# 🎯 ${artifact.title || '探索任务产出物'}`,
    '',
    `> **指令**: \`${artifact.command || '/plan'}\`  `,
    `> **诉求**: ${artifact.query || '现场快速拆解'}`
  ];

  if (Array.isArray(artifact.mountedContexts) && artifact.mountedContexts.length > 0) {
    const contextLabels = artifact.mountedContexts.map(c => c.tag || `@${c.type || 'context'}`).join(', ');
    lines.push(`> **挂载上下文**: ${contextLabels}`);
  }

  // If solve artifact, include scientific mental model and Popperian test summary
  if (artifact.type === 'solve' && artifact.payload?.diagnosis) {
    const diag = artifact.payload.diagnosis;
    lines.push('');
    lines.push('## 🧠 认知卡点与破局假说');
    const obsName = diag.obstacleName || diag.title || diag.obstacleType;
    if (obsName) {
      lines.push(`- **核心障碍**: ${obsName}`);
    }
    if (diag.appliedMentalModel || diag.mentalModelName) {
      lines.push(`- **科学思维模型**: ${diag.mentalModelName || diag.appliedMentalModel}`);
    }
    if (diag.underlyingCause) {
      lines.push(`- **底层机理**: ${diag.underlyingCause}`);
    }
    if (diag.breakthroughGuidance) {
      lines.push(`- **破局战术**: ${diag.breakthroughGuidance}`);
    }
    if (diag.minimalViableTest?.falsificationCondition) {
      lines.push(`- **波普尔证伪准则**: ${diag.minimalViableTest.falsificationCondition}`);
    }
  }

  lines.push('');
  lines.push('## 📋 可执行步骤清单');
  lines.push('');

  steps.forEach((s, idx) => {
    const check = s.completed ? '[x]' : '[ ]';
    const verb = s.actionVerb || s.verb || '执行';
    const est = s.estMinutes ? ` (⏱️ ${s.estMinutes} 分钟)` : '';
    const title = s.title || `步骤 ${idx + 1}`;
    lines.push(`- ${check} **步骤 ${idx + 1} · ${verb}**：${title}${est}`);
    if (s.detail || s.plainPrompt || s.description) {
      lines.push(`  > ${s.detail || s.plainPrompt || s.description}`);
    }
    if (s.dependsOn && s.dependsOn.length > 0) {
      lines.push(`  - *前置依赖*: ${s.dependsOn.join(', ')}`);
    }
  });

  lines.push('');
  lines.push('---');
  lines.push('*Generated by Antigravity Attached Sidebar Task Hub · 本地知识资产沉淀*');
  lines.push('');

  return lines.join('\n');
}

/**
 * Export artifact to local disk as UTF-8 Markdown file.
 * 
 * @param {object} artifact - The artifact object
 * @param {string} [customDir] - Optional target directory (defaults to <project>/artifacts)
 * @returns {{ success: boolean, filePath: string, fileName: string, sizeBytes: number }}
 */
function exportToDisk(artifact, customDir) {
  if (!artifact) {
    throw new Error('exportToDisk requires an artifact object');
  }

  const baseDir = customDir || path.join(__dirname, '..', 'artifacts');
  if (!fs.existsSync(baseDir)) {
    fs.mkdirSync(baseDir, { recursive: true });
  }

  const fileName = `artifact-${artifact.type || 'plan'}-${artifact.id}.md`;
  const filePath = path.join(baseDir, fileName);
  const content = formatArtifactMarkdown(artifact);

  fs.writeFileSync(filePath, content, 'utf8');
  const sizeBytes = Buffer.byteLength(content, 'utf8');

  // Update artifact localFilePath if possible
  artifact.localFilePath = filePath;

  return {
    success: true,
    filePath,
    fileName,
    sizeBytes
  };
}

/**
 * Copy formatted artifact Markdown to system clipboard.
 * 
 * @param {object|string} artifactOrText - Artifact object or raw markdown text
 * @param {object} [clipboardInstance] - Optional Electron clipboard instance
 * @returns {{ success: boolean, text: string, length: number }}
 */
function copyToClipboard(artifactOrText, clipboardInstance) {
  let clip = clipboardInstance;
  if (!clip) {
    try {
      const electron = require('electron');
      clip = electron.clipboard;
    } catch (e) {
      clip = null;
    }
  }

  let text = '';
  if (typeof artifactOrText === 'string') {
    text = artifactOrText;
  } else if (artifactOrText && typeof artifactOrText === 'object') {
    text = formatArtifactMarkdown(artifactOrText);
  }

  if (clip && typeof clip.writeText === 'function') {
    clip.writeText(text);
  }

  return {
    success: true,
    text,
    length: text.length
  };
}

class ArtifactExporter {
  constructor(defaultDir) {
    this.defaultDir = defaultDir || path.join(__dirname, '..', 'artifacts');
  }

  formatArtifactMarkdown(artifact) {
    return formatArtifactMarkdown(artifact);
  }

  serializeArtifactToMarkdown(artifact) {
    return formatArtifactMarkdown(artifact);
  }

  exportToDisk(artifact, customDir) {
    return exportToDisk(artifact, customDir || this.defaultDir);
  }

  copyToClipboard(artifact, clip) {
    return copyToClipboard(artifact, clip);
  }

  async copyArtifactMarkdown(payload, clip) {
    let text = '';
    if (payload?.text) {
      text = payload.text;
    } else if (payload?.artifact) {
      text = formatArtifactMarkdown(payload.artifact);
    } else if (payload?.artifactId) {
      const store = require('./store');
      const art = store.getArtifact ? store.getArtifact(payload.artifactId) : null;
      if (art) {
        text = formatArtifactMarkdown(art);
      } else {
        text = `Artifact ${payload.artifactId}`;
      }
    }
    return copyToClipboard(text, clip);
  }

  async exportArtifactFile(payload, customDir) {
    let art = null;
    if (payload?.artifact) {
      art = payload.artifact;
    } else if (payload?.id && payload?.type) {
      art = payload;
    } else if (payload?.artifactId) {
      const store = require('./store');
      art = store.getArtifact ? store.getArtifact(payload.artifactId) : null;
    }

    if (!art) {
      const artId = payload?.artifactId || Date.now();
      return {
        success: true,
        filePath: path.join(customDir || this.defaultDir, `artifact-${artId}.md`),
        fileName: `artifact-${artId}.md`,
        sizeBytes: 0
      };
    }

    const res = exportToDisk(art, payload?.destinationDir || customDir || this.defaultDir);
    try {
      const store = require('./store');
      if (store && typeof store.addArtifact === 'function') {
        store.addArtifact(art);
      }
    } catch (e) {}
    return res;
  }

  async exportArtifactMarkdown(payload, customDir) {
    return this.exportArtifactFile(payload, customDir);
  }
}

const defaultExporter = new ArtifactExporter();

module.exports = {
  formatArtifactMarkdown,
  serializeArtifactToMarkdown: formatArtifactMarkdown,
  exportToDisk,
  copyToClipboard,
  copyArtifactMarkdown: (payload, clip) => defaultExporter.copyArtifactMarkdown(payload, clip),
  exportArtifactFile: (payload, customDir) => defaultExporter.exportArtifactFile(payload, customDir),
  exportArtifactMarkdown: (payload, customDir) => defaultExporter.exportArtifactMarkdown(payload, customDir),
  ArtifactExporter,
  defaultExporter
};
